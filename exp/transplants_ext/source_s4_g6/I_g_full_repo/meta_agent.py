from agent.base_agent import AgentSystem
from agent.llm_withtools import chat_with_agent

class MetaAgent(AgentSystem):
    def forward(self, repo_path, eval_path, iterations_left=None):
        """
        A meta agent that recursively self-improves.

        Args:
            repo_path (str): The path to the repository.
            eval_path (str): The path to previously generated agents and their evaluation results.
            iterations_left (int, optional): The number of remaining iterations in which the meta agent will be invoked in future. Defaults to None.
        """
        instruction = f"Improve the agent-generation system in the codebase at `{repo_path}`."
        instruction += (
            f"\n\nThe README.md describes the goal. Prior generations and evaluation results are at `{eval_path}`. "
            "Work autonomously; do not ask questions. First inspect the relevant source and the prior generations' "
            "metadata, evaluation reports, source patches, and logs. Identify the strongest valid generation from "
            "comparable completed evaluations, and use its results and the failed cases to motivate one focused "
            "improvement. Treat a missing evaluation as unknown, not as a score. Make and validate a useful source "
            "change; do not make cosmetic or artifact-only changes. Avoid editing `domains/` because those changes "
            "are reverted by the runner, and do not include generated bytecode, caches, or evaluation outputs in "
            "your change. Use the tools to inspect, edit, and validate; only finish once the work is done."
        )

        new_msg_history = chat_with_agent(instruction, model=self.model, msg_history=[], logging=self.log, tools_available='all')
